/**
 * 定时任务单次运行的步数上限（一步 = 一次模型请求及其工具调用）。只管定时任务：它无人值守，上下文又会
 * 自动压缩、永远不会满，模型一旦兜圈子就会一直跑下去。普通对话与子智能体运行时用户在场，不设上限。
 * 到达上限后不再执行工具，另给模型一次收尾请求让它总结（见 chat.ts runAgentLoop），本次运行记为失败。
 */
export const TASK_MAX_STEPS = 100

/**
 * 原地打转：同一工具、同样参数、同样结果连续出现的次数（普通对话、子智能体、定时任务都适用）。
 * 只看参数不够——截图等页面加载、轮询构建状态这类调用参数相同而结果在变，是正常的；三者都相同才是没有进展。
 * 到 REPEAT_WARN 次起在工具结果后附一句提醒；到 REPEAT_STOP 次停止调用工具，收尾方式同步数上限。
 */
export const REPEAT_WARN = 3
export const REPEAT_STOP = 5
